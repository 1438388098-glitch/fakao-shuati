function t(lang, key, vars) {
  let s = (dict[lang] && dict[lang][key] != null) ? dict[lang][key] : dict.zh[key];
  if (s == null) return key;
  if (vars) for (const k of Object.keys(vars)) s = s.split('{' + k + '}').join(String(vars[k]));
  return s;
}

